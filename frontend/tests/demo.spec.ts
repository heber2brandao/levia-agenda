import { test, expect } from '@playwright/test'

test('conta sem configuração não simula autenticação', async ({ page }) => {
  await page.goto('/conta')
  await expect(page.getByRole('heading', { name: 'Vamos conectar seu espaço' })).toBeVisible()
  await expect(page.getByText(/Nenhuma conta foi criada/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Entrar', exact: true })).toHaveCount(0)
})

test('navegação, catálogo e fluxo público claramente demonstrativo', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Bom dia, Ana.' })).toBeVisible()
  await page.getByRole('link', { name: 'Serviços', exact: true }).click()
  await page.getByRole('button', { name: 'Novo serviço' }).click()
  await page.getByLabel('Nome do serviço').fill('Spa das mãos')
  await page.getByLabel('Valor (R$)').fill('60')
  await page.getByRole('button', { name: 'Salvar na demonstração' }).click()
  await expect(page.getByRole('heading', { name: 'Spa das mãos' })).toBeVisible()
  await page.getByRole('button', { name: 'Desativar', exact: true }).first().click()
  await page.getByRole('link', { name: 'Visão geral' }).click()
  await page.getByRole('link', { name: 'Ver página pública' }).click()
  await expect(page.getByRole('button', { name: /^Manicure/ })).toHaveCount(0)
  await page.getByRole('button', { name: /Spa das mãos/ }).click()
  await page.getByRole('button', { name: /^Pedicure/ }).click()
  await expect(page.getByRole('status')).toContainText('2 serviços selecionados')
  await expect(page.getByRole('status')).toContainText('105 minutos')
  await expect(page.getByRole('status')).toContainText(/R\$\s*105,00/)
  await page.getByLabel('Data desejada').fill('2099-10-10')
  await page.getByRole('button', { name: '09:00', exact: true }).click()
  await page.getByRole('button', { name: /^Pedicure/ }).click()
  await expect(page.getByRole('button', { name: /Concluir simulação/ })).toHaveCount(0)
  await expect(page.getByRole('status')).toContainText('45 minutos')
  await page.getByRole('button', { name: /Spa das mãos/ }).click()
  await expect(page.getByLabel('Data desejada')).toHaveCount(0)
  await page.getByRole('button', { name: /Spa das mãos/ }).click()
  await page.getByRole('button', { name: /^Pedicure/ }).click()
  await page.getByRole('button', { name: '09:00', exact: true }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Cliente de teste')
  await page.getByLabel('Telefone com DDD').fill('65999999999')
  await expect(page.getByRole('checkbox')).not.toBeChecked()
  await page.getByRole('button', { name: /Concluir simulação/ }).click()
  await expect(page.getByText('Nenhum horário foi reservado e nenhuma mensagem foi enviada.')).toBeVisible()
  await expect(page.getByText(/Simulação de Pedicure \+ Spa das mãos/)).toBeVisible()
  await expect(page.getByText(/2 serviço\(s\) · 105 minutos/)).toBeVisible()
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

test('agenda, clientes, perfil e rota inexistente', async ({ page }) => {
  await page.goto('/agenda')
  await page.getByRole('button', { name: 'Semana', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sex 2' })).toBeVisible()
  await page.getByRole('link', { name: 'Clientes', exact: true }).click()
  await page.getByLabel('Buscar cliente fictícia').fill('inexistente')
  await expect(page.getByText('Nenhuma cliente encontrada.')).toBeVisible()
  await page.getByRole('link', { name: 'Meu espaço' }).click()
  await page.getByLabel('Seu nome', { exact: true }).fill('Fernanda KieleK')
  await page.getByLabel('Telefone', { exact: true }).fill('65999999999')
  await page.getByRole('button', { name: 'Salvar perfil nesta sessão' }).click()
  await expect(page.getByRole('status')).toContainText('Perfil atualizado nesta sessão')
  await expect(page.getByRole('heading', { name: 'Ateliê Fernanda KieleK' })).toBeVisible()
  await page.getByRole('link', { name: 'Ver página personalizada' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Ateliê Fernanda KieleK' })).toBeVisible()
  await page.getByRole('link', { name: /Voltar ao painel/ }).click()
  await expect(page.getByRole('heading', { name: 'Bom dia, Fernanda.' })).toBeVisible()
  await page.getByRole('link', { name: 'Meu espaço' }).click()
  await expect(page.getByLabel('Seu nome', { exact: true })).toHaveValue('Fernanda KieleK')
  await expect(page.getByLabel('Telefone', { exact: true })).toHaveValue('65999999999')
  await page.getByLabel('Nome do espaço', { exact: true }).fill('Studio Bela Flor')
  await page.getByRole('button', { name: 'Salvar perfil nesta sessão' }).click()
  await page.getByLabel('Seu nome', { exact: true }).fill('Maria Silva')
  await page.getByRole('button', { name: 'Salvar perfil nesta sessão' }).click()
  await expect(page.getByRole('heading', { name: 'Studio Bela Flor' })).toBeVisible()
  await page.goto('/nao-existe')
  await expect(page.getByRole('heading', { name: 'Página não encontrada' })).toBeVisible()
})
